function ModelCatalogSettings() {
  const models = useAppStore((s) => s.models);
  const selectedModel = useAppStore((s) => s.selectedModel);
  const setModels = useAppStore((s) => s.setModels);
  const setSelectedModel = useAppStore((s) => s.setSelectedModel);
  const [cloudModels, setCloudModels] = useState<CloudModelInfo[]>([]);
  const [tab, setTab] = useState<'local' | 'cloud'>(() => (
    isCloudModel(selectedModel) ? 'cloud' : 'local'
  ));
  const [query, setQuery] = useState('');
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState('');
  const [lastUpdated, setLastUpdated] = useState<number | null>(null);

  const refresh = useCallback(async () => {
    setLoading(true);
    setError('');
    const [localResult, cloudResult] = await Promise.allSettled([
      fetchModels(),
      fetchCloudModels(),
    ]);
    if (localResult.status === 'fulfilled') setModels(localResult.value);
    if (cloudResult.status === 'fulfilled') setCloudModels(cloudResult.value);
    if (
      (localResult.status !== 'fulfilled' || localResult.value.length === 0) &&
      cloudResult.status === 'fulfilled' && cloudResult.value.length > 0
    ) {
      setTab((current) => current === 'local' ? 'cloud' : current);
    }
    const failures = [localResult, cloudResult]
      .filter((result): result is PromiseRejectedResult => result.status === 'rejected');
    if (failures.length > 0) {
      setError(failures.map((failure) => failure.reason?.message || 'catalog unavailable').join(' · '));
    }
    setLastUpdated(Date.now());
    setLoading(false);
  }, [setModels]);

  useEffect(() => {
    void refresh();
    window.addEventListener(CLOUD_KEY_STATUS_CHANGED, refresh);
    return () => window.removeEventListener(CLOUD_KEY_STATUS_CHANGED, refresh);
  }, [refresh]);

  const localFiltered = models.filter((model) =>
    `${model.id} ${model.owned_by}`.toLowerCase().includes(query.trim().toLowerCase()),
  );
  const cloudFiltered = cloudModels.filter((model) =>
    `${model.id} ${model.name} ${model.owned_by}`.toLowerCase().includes(query.trim().toLowerCase()),
  );
  const visibleCount = tab === 'local' ? localFiltered.length : cloudFiltered.length;

  const chooseModel = (modelId: string) => {
    setSelectedModel(modelId);
  };

  const modelButton = (id: string, label: string, description: string) => {
    const active = selectedModel === id;
    return (
      <button
        key={id}
        type="button"
        onClick={() => chooseModel(id)}
        className="w-full text-left rounded-lg px-3 py-2 cursor-pointer transition-colors"
        style={{
          background: active ? 'var(--color-accent-soft, var(--color-bg-tertiary))' : 'var(--color-bg)',
          border: `1px solid ${active ? 'var(--color-accent)' : 'var(--color-border)'}`,
          color: 'var(--color-text)',
        }}
        aria-pressed={active}
      >
        <div className="flex items-center justify-between gap-2">
          <span className="text-xs font-medium truncate">{label}</span>
          {active && <Check size={14} style={{ color: 'var(--color-success)', flexShrink: 0 }} />}
        </div>
        <div className="text-[10px] mt-1 truncate" style={{ color: 'var(--color-text-tertiary)' }}>{description}</div>
      </button>
    );
  };

  return (
    <div className="space-y-3">
      <div className="flex items-center justify-between gap-2">
        <div className="text-xs" style={{ color: 'var(--color-text-secondary)' }}>
          Escolha aqui o modelo padrão do chat. A seleção é salva localmente e também aparece no seletor do chat.
        </div>
        <button
          type="button"
          onClick={() => void refresh()}
          disabled={loading}
          className="inline-flex items-center gap-1 px-2 py-1 rounded text-xs cursor-pointer"
          style={{ color: 'var(--color-accent)', border: '1px solid var(--color-border)', opacity: loading ? 0.6 : 1 }}
          title="Atualizar catálogo de modelos"
        >
          <RefreshCw size={12} className={loading ? 'animate-spin' : ''} />
          Atualizar
        </button>
      </div>

      <div className="flex items-center gap-2">
        <button type="button" onClick={() => setTab('local')} className="px-3 py-1.5 rounded-lg text-xs cursor-pointer"
          style={{ background: tab === 'local' ? 'var(--color-accent)' : 'var(--color-bg-tertiary)', color: tab === 'local' ? 'white' : 'var(--color-text-secondary)' }}>
          Local / Ollama ({models.length})
        </button>
        <button type="button" onClick={() => setTab('cloud')} className="px-3 py-1.5 rounded-lg text-xs cursor-pointer"
          style={{ background: tab === 'cloud' ? 'var(--color-accent)' : 'var(--color-bg-tertiary)', color: tab === 'cloud' ? 'white' : 'var(--color-text-secondary)' }}>
          OpenRouter ({cloudModels.length})
        </button>
      </div>

      <div className="flex items-center gap-2 px-3 py-2 rounded-lg" style={{ background: 'var(--color-bg)', border: '1px solid var(--color-border)' }}>
        <Search size={14} style={{ color: 'var(--color-text-tertiary)' }} />
        <input
          type="search"
          value={query}
          onChange={(event) => setQuery(event.target.value)}
          placeholder={tab === 'local' ? 'Buscar modelo local...' : 'Buscar modelo OpenRouter...'}
          className="w-full bg-transparent outline-none text-xs"
          style={{ color: 'var(--color-text)' }}
          aria-label="Buscar modelos"
        />
      </div>

      {tab === 'cloud' && cloudModels.length === 0 && !loading && (
        <div className="rounded-lg px-3 py-2 text-xs" style={{ background: 'var(--color-bg-tertiary)', color: 'var(--color-text-secondary)' }}>
          Configure uma chave OpenRouter abaixo e clique em Atualizar para carregar o catálogo real de modelos.
        </div>
      )}
      {error && <div className="text-xs" style={{ color: 'var(--color-error)' }}>{error}</div>}
      {!loading && visibleCount === 0 && !error && (
        <div className="text-xs" style={{ color: 'var(--color-text-tertiary)' }}>Nenhum modelo encontrado.</div>
      )}
      <div className="grid grid-cols-1 md:grid-cols-2 gap-2 max-h-72 overflow-y-auto pr-1">
        {tab === 'local'
          ? localFiltered.map((model: ModelInfo) => modelButton(model.id, model.id, `Local · ${model.owned_by}`))
          : cloudFiltered.map((model) => modelButton(model.id, model.name || model.id.replace(/^openrouter\//, ''), model.id))}
      </div>
      <div className="flex items-center justify-between text-[10px]" style={{ color: 'var(--color-text-tertiary)' }}>
        <span>Modelo ativo: {selectedModel || 'nenhum selecionado'}</span>
        <span>{lastUpdated ? `Atualizado às ${new Date(lastUpdated).toLocaleTimeString()}` : ''}</span>
      </div>
    </div>
  );
}

function ApiKeyInput({
  keyName,
  placeholder,
  toolName,
}: {
  keyName: string;
  placeholder: string;
  toolName?: string;
}) {
  const [value, setValue] = useState('');
  const [saved, setSaved] = useState(false);
  const [hasKey, setHasKey] = useState(false);
  const [error, setError] = useState('');
  const desktopKeyStorage = isTauri();
  const serverToolStorage = !desktopKeyStorage && !!toolName;
  const browserCloudStorage = !desktopKeyStorage && !toolName;
  const canManage = desktopKeyStorage || serverToolStorage || browserCloudStorage;

  const refresh = useCallback(async () => {
    if (!canManage) {
      setHasKey(false);
      return;
    }
    try {
      const status = desktopKeyStorage || browserCloudStorage
        ? await getCloudKeyStatus()
        : await fetchToolCredentialStatus(toolName!);
      setHasKey(!!status[keyName]);
    } catch {
      setHasKey(false);
    }
  }, [canManage, desktopKeyStorage, keyName, toolName]);

  useEffect(() => {
    void refresh();
    window.addEventListener(CLOUD_KEY_STATUS_CHANGED, refresh);
    return () => window.removeEventListener(CLOUD_KEY_STATUS_CHANGED, refresh);
  }, [refresh]);

  const save = async (v: string) => {
    const next = v.trim();
    if (!next) return;
    setError('');
    try {
      if (desktopKeyStorage) {
        await saveCloudKey(keyName, next);
      } else if (toolName) {
        await saveToolCredentials(toolName, { [keyName]: next });
      } else {
        await saveCloudKey(keyName, next);
      }
      setValue('');
      setHasKey(true);
      setSaved(true);
      window.dispatchEvent(new Event(CLOUD_KEY_STATUS_CHANGED));
      setTimeout(() => setSaved(false), 2000);
    } catch (e: any) {
      setError(e?.message || 'Failed to save API key');
    }
  };

  const remove = async () => {
    setError('');
    try {
      if (desktopKeyStorage) {
        await saveCloudKey(keyName, '');
      } else if (toolName) {
        await deleteToolCredential(toolName, keyName);
      } else {
        await saveCloudKey(keyName, '');
      }
      setValue('');
      setHasKey(false);
      setSaved(true);
      window.dispatchEvent(new Event(CLOUD_KEY_STATUS_CHANGED));
      setTimeout(() => setSaved(false), 2000);
    } catch (e: any) {
      setError(e?.message || 'Failed to remove API key');
    }
  };

  return (
    <div className="flex items-center gap-2">
      <input
        type="password"
        value={value}
        onChange={e => setValue(e.target.value)}
        onKeyDown={e => {
          if (e.key === 'Enter' && value.trim()) {
            e.currentTarget.blur();
          }
        }}
        onBlur={() => { if (value.trim()) void save(value); }}
        placeholder={hasKey ? (desktopKeyStorage ? 'Saved in secure storage' : 'Saved by local server') : placeholder}
        className="w-48 px-2 py-1 rounded text-xs"
        style={{ background: 'var(--color-bg)', border: '1px solid var(--color-border)', color: 'var(--color-text)' }} />
      {hasKey && (
        <button
          onClick={() => void remove()}
          className="px-2 py-1 rounded text-[10px] cursor-pointer"
          style={{ color: 'var(--color-error)', border: '1px solid var(--color-error)' }}
        >
          Remove
        </button>
      )}
      {saved && <span className="text-[10px]" style={{ color: 'var(--color-success)' }}>Saved</span>}
      {error && <span className="text-[10px]" style={{ color: 'var(--color-error)' }}>{error}</span>}
    </div>
  );
}

